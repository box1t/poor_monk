c, n = map(int, input().split())

    # Логика принятия решений:
    # 1. Сначала максимизируем коров: Выигрыш > Ничья > Проигрыш
    # 2. Затем максимизируем монеты: Минимизируем ставку 'b'
if n > c:
        # Случай 1: Вы можете выиграть корову (b > c).
        # Поскольку у вас достаточно монет (n > c), вы можете поставить b = c + 1.
        # Это наилучший исход по коровам.
        # Чтобы максимизировать монеты, вы должны сделать минимально возможную выигрышную ставку.
    optimal_bet = c + 1
elif n == c:
        # Случай 2: Вы не можете выиграть (для этого нужно b >= c + 1, но у вас только n = c).
        # Однако вы можете сыграть вничью (b = c).
        # Это наилучший возможный исход по коровам.
        # Единственная ставка для ничьей — это b = c.
    optimal_bet = c
else:  # n < c
        # Случай 3: Вы не можете ни выиграть, ни сыграть вничью (b <= n < c).
        # Вы обязательно проиграете корову.
        # Поскольку исход по коровам фиксирован (проигрыш), мы максимизируем монеты.
        # Чтобы максимизировать монеты (n - b + c), нужно минимизировать ставку 'b'.
        # Минимально возможная ставка — b = 0.
    optimal_bet = 0

print(optimal_bet)

