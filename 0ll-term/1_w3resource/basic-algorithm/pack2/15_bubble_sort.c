// Write a bubble sort

#include <stdio.h>

void bubble_sort(int arr[], int arr_sz) {
    // Внешний цикл: количество проходов по массиву
    // Поскольку внешний цикл (i) гарантирует, что после каждого прохода i элементов в конце массива уже стоят на своих правильных местах, 
    // внутреннему циклу (j) бессмысленно проверять их снова.
    for (int i = 0; i < arr_sz - 1; ++i) {
        
        // Внутренний цикл: сравнение соседних элементов
        // Обратите внимание: arr_sz - 1 - i. 
        // После каждого прохода (i) самый большой элемент "всплывает" в конец,
        // поэтому нам не нужно проверять последние i элементов снова.
        for (int j = 0; j < arr_sz - 1 - i; ++j) {
            
            // Сравниваем именно текущий элемент (j) со следующим (j + 1)
            if (arr[j] > arr[j + 1]) {
                int temp = arr[j];
                arr[j] = arr[j + 1];
                arr[j + 1] = temp;
            }
        }
    }
}

int main() {
    int arr[] = {14, 2, 3, 3, 18, 1, 5, 1, 15};
    int arr_sz = sizeof(arr) / sizeof(arr[0]);
    bubble_sort(arr, arr_sz);
    for (int i = 0; i < arr_sz; ++i) {
        printf("%d ", arr[i]);
    }
}