// Write a C program, which adds up columns and rows of given table. develop a small part of spreadsheet software

#include <stdio.h>

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0; // Защита от некорректного ввода

    // 1. Объявляем массив с запасом на 1 строку и 1 столбец
    int arr[n + 1][n + 1];

    // 2. ОБЯЗАТЕЛЬНО обнуляем последнюю строку и последний столбец!
    // В C локальные переменные содержат "мусор", если их не обнулить.
    for (int i = 0; i <= n; i++) {
        arr[i][n] = 0; // Обнуляем последний столбец
        arr[n][i] = 0; // Обнуляем последнюю строку
    }

    // 3. Читаем матрицу и СРАЗУ считаем суммы
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            scanf("%d", &arr[i][j]);
            
            // Прибавляем текущий элемент к сумме его строки
            arr[i][n] += arr[i][j];
            
            // Прибавляем текущий элемент к сумме его столбца
            arr[n][j] += arr[i][j];
            
            // Прибавляем текущий элемент к общей сумме (правый нижний угол)
            arr[n][n] += arr[i][j];
        }
    }

    // 4. Выводим результат (размер теперь n+1 на n+1)
    for (int i = 0; i <= n; i++) {
        for (int j = 0; j <= n; j++) {
            printf("%d ", arr[i][j]);
        }
        printf("\n");
    }

    return 0;
}