// Поразрядная конъюнкция двоичных чисел

#include <stdio.h>

// Вспомогательная функция для вывода числа в двоичном виде
void print_binary(unsigned int n) {
    // Проходим по всем 32 битам числа (от старшего к младшему)
    for (int i = 31; i >= 0; i--) {
        // Сдвигаем число вправо на i позиций и берем младший бит (& 1)
        // Выражение (n >> i) сдвигает биты числа n вправо на i позиций, помещая нужный нам бит на самую правую (младшую) позицию.
        // Операция & 1 "отсекает" все остальные биты, оставляя только текущий (он будет равен либо 0, либо 1).
        int bit = (n >> i) & 1; 
        printf("%d", bit);
        
        // Добавляем пробел каждые 4 бита для удобства чтения (например: 0000 1010)
        if (i % 4 == 0 && i != 0) {
            printf(" ");
        }
    }
}

int main() {
    unsigned int num1, num2, result;

    printf("=== Поразрядная конъюнкция (Bitwise AND) ===\n");
    printf("Введите первое число (в десятичном виде): ");
    scanf("%u", &num1);
    
    printf("Введите второе число (в десятичном виде): ");
    scanf("%u", &num2);

    // Сама операция поразрядной конъюнкции
    result = num1 & num2;

    printf("\n--- Результат ---\n");
    
    printf("Число 1 (dec): %u\n", num1);
    printf("Число 1 (bin): ");
    print_binary(num1);
    printf("\n");

    printf("Число 2 (dec): %u\n", num2);
    printf("Число 2 (bin): ");
    print_binary(num2);
    printf("\n");

    printf("Результат(dec): %u\n", result);
    printf("Результат(bin): ");
    print_binary(result);
    printf("\n");

    printf("\nПравило конъюнкции: 1 & 1 = 1, во всех остальных случаях = 0\n");

    return 0;
}