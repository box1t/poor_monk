// Write a C program to output the alphabet along with ASCII values and their binary representations.

#include <stdio.h>

// Функция для вывода 8-битного двоичного представления числа
void printBinary(int num) {
    // ASCII коды букв помещаются в 8 бит (1 байт).
    // Проходим от старшего бита (7) к младшему (0). (в правильном порядке)
    for (int i = 7; i >= 0; i--) {
        // (num >> i) сдвигает биты вправо на i позиций.
        // & 1 оставляет только самый младший бит (0 или 1). это побитовое И, маска.
        printf("%d", (num >> i) & 1);
    }
}

int main() {
    // Выводим заголовок таблицы для красоты
    printf("Символ | ASCII (Dec) | Binary\n");
    printf("-------------------------------\n");

    // 1. Вывод строчных букв (a-z)
    for (char c = 'a'; c <= 'z'; c++) {
        // %-5c выравнивает символ по левому краю в поле из 5 символов
        // %3d выравнивает число по правому краю в поле из 3 символов
        printf("   %c   |    %3d    | ", c, c); // В C тип char — это по сути маленькое целое число. 
        // компилятор автоматически берет числовое значение этого символа из таблицы ASCII
        
        printBinary(c); 
        printf("\n");
    }

    printf("-------------------------------\n");

    // 2. Вывод прописных букв (A-Z)
    for (char c = 'A'; c <= 'Z'; c++) {
        printf("   %c   |    %3d    | ", c, c);
        printBinary(c);
        printf("\n");
    }

    return 0;
}