// "подсчет вхождений каждого числа в массиве"

#include <stdio.h>

int main() {
    int n;
    int a[100];

    printf("Введите количество элементов массива: ");
    scanf("%d", &n);

    printf("Введите элементы массива:\n");
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]);
    }

    for (int i = 0; i < n; i++) {
        int count = 0;
        int already_counted = 0;

        // Проверяем, встречалось ли число раньше
        for (int j = 0; j < i; j++) {
            if (a[i] == a[j]) {
                already_counted = 1;
                break;
            }
        }

        // Если число ещё не подсчитывали
        if (!already_counted) {
            for (int j = 0; j < n; j++) {
                if (a[i] == a[j]) {
                    count++;
                }
            }

            printf("%d встречается %d раз(а)\n", a[i], count);
        }
    }

    return 0;
}



