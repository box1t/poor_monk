// Write a C program to track and display all positions where the highest value occurs in the input list.

#include <stdio.h>

int main() {
    int n;
    // Считываем количество элементов
    if (scanf("%d", &n) != 1 || n <= 0) {
        return 0; 
    }

    int arr[n];
    for (int i = 0; i < n; ++i) {
        scanf("%d", &arr[i]);
    }

    int pos[n];       // Массив для хранения позиций (индексов) - track and display all positions
    int max = arr[0]; // Изначально максимум - первый элемент
    int count = 0;    // Счетчик найденных позиций максимального элемента
    // две проблемы: 1 - сохранять значение позиции, 2 - перезаписывать массив позиций при обновлении максимума, обнулять предыдущие записи

    // Пройдись по всем элементам массива по порядку, начиная с самого первого (индекс 0) и заканчивая последним (индекс n-1), делая по одному шагу за раз
    // иду по исходному массиву элемент за элементом
    for (int i = 0; i < n; ++i) {
        if (arr[i] > max) {
            // НАШЛИ НОВЫЙ МАКСИМУМ!
            max = arr[i];      // Обновляем максимум
            count = 0;         // Стираем старые данные логически: сбрасываем счетчик, старые позиции неактуальны, больше не нужны
            // Следующая запись пойдет в самую первую ячейку pos[0], перетирая старые данные»).
            // Забудь всё, что мы записали ранее. Начни заполнять массив результатов с самого начала, как будто он новый

            pos[count] = i + 1; // Записываем первую позицию нового максимума на текущем шаге цикла. 
            // "кладу эту позицию в массив результатов pos, ровно на то свободное место, которое указывает мой счетчик"
            // pos[i] - адрес в массиве результатов, в него записываем реальную позицию числа в исходном массиве
            // "записываю порядковый номер на следующую свободную строчку, которую мне подсказывает счетчик"
            count++;           // Готовимся к следующей возможной записи, Увеличиваем счетчик
        }
        else if (arr[i] == max) {
            // НАШЛИ ТЕКУЩИЙ МАКСИМУМ ПОВТОРНО
            pos[count] = i + 1; // Записываем позицию максимума на текущем шаге цикла ровно на то свободное место, которое указывает счетчик
            count++;            // Готовимся к следующей возможной записи, Увеличиваем счетчик
        }
    }

    // выводим на экран все записанные позиции. проходим по всем полезным ячейкам массива позиций
    for (int i = 0; i < count; ++i) {
        printf("%d ", pos[i]);
    }
    printf("\n");

    return 0;
}