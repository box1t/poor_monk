// Переставь выбранные байты числа местами

// побитовые операции: сдвиги (>>, <<), побитовое И (&) для извлечения, и побитовое ИЛИ (|) для вставки.

#include <stdio.h>
#include <stdint.h>

// Функция меняет местами байты с индексами pos1 и pos2
// Индексы байтов: 0 (самый младший) ... 3 (самый старший)
uint32_t swap_bytes(uint32_t num, int pos1, int pos2) {
    // 1. Извлекаем нужные байты (маска 0xFF оставляет только 8 бит)
    uint8_t byte1 = (num >> (pos1 * 8)) & 0xFF;
    uint8_t byte2 = (num >> (pos2 * 8)) & 0xFF;

    // 2. Очищаем эти байты в исходном числе (заменяем их на нули)
    // ~(0xFF << смещение) создает маску с нулями на месте целевого байта и единицами везде else
    num &= ~(0xFF << (pos1 * 8));
    num &= ~(0xFF << (pos2 * 8));

    // 3. Вставляем извлеченные байты на новые позиции
    num |= (byte1 << (pos2 * 8));
    num |= (byte2 << (pos1 * 8));

    return num;
}

int main() {
    // Пример: число 0x12345678
    // Байт 0: 0x78, Байт 1: 0x56, Байт 2: 0x34, Байт 3: 0x12
    uint32_t number = 0x12345678;
    
    printf("Исходное число: 0x%08X\n", number);

    // Поменяем местами байт 0 (0x78) и байт 2 (0x34)
    uint32_t result = swap_bytes(number, 0, 2);

    printf("После замены 0 и 2: 0x%08X\n", result);

    return 0;
}