// Write a C program to identify duplicate elements in an array and replace them with a sentinel value, such as -1.

#include <stdio.h>
int main() {
    int n;
    scanf("%d", &n);

    int arr[n];

    for (int i = 0; i < n; i++) {
        scanf("%d", &arr[i]);
    }

    // i от 0 до n: Чтобы каждый элемент побывал в роли «эталона».
    // Переменная i - эталонный индекс
    // «А есть ли такие же элементы, как этот, дальше в массиве?».
    for (int i = 0; i < n; i++) {

        // Если бы мы не сделали эту проверку, программа взяла бы -1 как «эталон» и начала бы искать другие -1, чтобы заменить их на -1.
        if (arr[i] == -1) {
            continue; 
        }

        // Ищем совпадения ТОЛЬКО впереди стоящих элементов
        // это гарантирует, что мы никогда не сравним элемент сам с собой 
        // и не будем делать лишнюю работу, проверяя элементы, которые уже были обработаны на предыдущих шагах внешнего цикла.
        // Переменная j - искательный индекс - проверяет элементы, которые идут после элемента с эталонным индексом
        // 1. Не сравниваем элемент сам с собой, иначе на первой же итерации программа бы уничтожила эталон, сравнив сам с собой
        // 2. Не делаем двойную работу, смотрим только вперед

        // j от i + 1 до n: Чтобы искать дубликаты только впереди, не трогая сам эталон и не делая лишних сравнений с уже проверенными элементами.
        for (int j = i + 1; j < n; j++) {

            if (arr[i] == arr[j]) {
                arr[j] = -1; // Заменяем только повторное вхождение
            }

        }
    }
    // Вывод результата
    for (int i = 0; i < n; i++) {
        printf("%d ", arr[i]);
    }

    return 0;
}