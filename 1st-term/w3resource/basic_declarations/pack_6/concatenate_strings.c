// concatenate two strings

#include <stdio.h>

int main() {
    char str1[100] = "Hello";
    char str2[] = " World";

    int i = 0;
    int j = 0;


    /*
    // Философия: Счетчик vs. Состояние
    // Цикл for создан для счетчиков. Он идеален, когда у тебя есть одна переменная, которая меняется с предсказуемым, фиксированным шагом
    // Цикл while создан для состояний. Он идеален, когда условие продолжения зависит от сложной логики или состояния системы, а не от простого подсчета
    // Цикл while честно говорит: "Здесь есть условие. А всё, что нужно сделать, чтобы это условие когда-нибудь стало ложным, написано внутри тела цикла". 
    // Это делает код более честным и легким для отладки.

        3 причины, по которым здесь while предпочтительнее for:
    1. не знаем количество шагов заранее (даже несмотря на наличие счетчиков i, j). Это классическая задача поиска, а не подсчета
    2. Первый цикл с for выглядел бы уродливо - с пустым телом - плохой стиль программирования
    3. Во втором цикле меняются ДВЕ переменные
    Заголовок цикла for заточен под управление одной основной переменной цикла: for (инициализация; условие; шаг).
    Если мы попытаемся впихнуть сюда два счетчика, код станет менее читаемым.

    */

    // Находим конец первой строки
    while (str1[i] != '\0') {
        i++;
    }

    // Копируем вторую строку в конец первой
    while (str2[j] != '\0') {
        str1[i] = str2[j];
        i++;
        j++;
    }

    // Добавляем конец строки
    str1[i] = '\0';

    printf("%s\n", str1);

    return 0;
}