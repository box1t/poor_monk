
/*
Последовательность Фибоначчи образуется так: первые два числа равны 1 и 1, а каждый следующий равен сумме двух предыдущих. 
То есть, имеем последовательность вида: 1, 1, 2, 3, 5, 8, 13, ... 
Вычислите последовательность Фибоначчи длиной n (n - натуральное число, читаемое из входного потока). 
Выведите числа полученной последовательности в одну строку через пробел.

*/
#include <stdio.h>

int main() {
    int n;
    if (scanf("%d", &n) != 1 || n <= 0) return 0;

    long long first = 1, second = 1, next;

    for (int i = 1; i <= n; i++) {
        if (i <= 2) {
            // Первые два числа всегда 1
            printf("1 ");
        } else {
            next = first + second;
            printf("%lld ", next);
            // Сдвигаем значения: старое второе становится первым, 
            // новое становится вторым
            first = second;
            second = next;
        }
    }

    return 0;
}