// Write a C program to create an array taking the elements after the element value 5 from a given array of integers. 

#include <stdio.h>

/* 
В языке C все аргументы функций передаются по значению (by value). 
Это значит, что функция получает копию переменной.

Чтобы функция могла изменить оригинальную переменную, 
мы должны дать ей не копию значения, а точный адрес в памяти, где лежит эта переменная.
*/

// *dest_sz - Этот параметр является не обычным числом, 
// а указателем (то есть адресом в памяти), по которому лежит число типа int
void take_elements_after_5(int arr[], int arr_sz, int dest[], int *dest_sz) {
    int flag = 0;
    int dest_idx = 0;
    for (int i = 0; i < arr_sz; ++i){
        if (!flag) {
            if (arr[i] == 5) {
                flag = 1;
                continue; // нужен, потому что следующая встреченная 5 уже будет записана в массив 
            }
        }
        else {
            dest[dest_idx] = arr[i];
            ++dest_idx;
            // problem: что делать с массивом после записи в него данных?
        }
    }
    // solution:
    // "Перейди по адресу, который хранится в dest_sz, и измени значение, которое лежит по этому адресу"
    // *pointer = "Иди по этому адресу и прочитай/измени значение там" (используется внутри функции).
    * dest_sz = dest_idx;
}

/*
В C функция может сделать return только одного значения. 
Но в нашей задаче функции нужно "вернуть" две вещи:

    Сам новый массив (мы делаем это через аргумент dest[] или через return указателя из malloc).
    Размер этого нового массива.

Поскольку return уже занят (или мы хотим избежать malloc), 
мы используем этот трюк с указателем, чтобы функция 
могла "модифицировать" переменную из вызывающего кода как побочный эффект. 
*/

int main() {
    int arr[] = {1, 2, 3, 4, 5, 6};
    int arr_sz = sizeof(arr) / sizeof(arr[0]);
    int new_arr[arr_sz];
    int new_sz = 0;

    // Чтобы функция могла изменить оригинальную переменную, 
    // мы должны дать ей не копию значения, а точный адрес в памяти, где лежит эта переменная.
    // &variable = "Дай мне адрес этой переменной" (используется при вызове).
    take_elements_after_5(arr, arr_sz, new_arr, &new_sz);

}